def main():
    parser = argparse.ArgumentParser(description="IDE Guide Agentic Skill CLI")
    parser.add_argument("--ide", type=str, required=True, help="Name of the IDE or Code Editor")
    parser.add_argument("--repo", type=str, help="Optional git repository URL")
    parser.add_argument("--output-dir", type=str, default="generated_content", help="Directory to save output files")
    parser.add_argument("--format", choices=["both", "amp", "video"], default="both", help="Output format selection")

    args = parser.parse_args()

    ide_data = get_or_create_ide_info(args.ide, args.repo)
    out_dir = Path(args.output_dir)
    out_dir.mkdir(parents=True, exist_ok=True)

    slug = re.sub(r'[^a-z0-9]', '_', ide_data['name'].lower())

    if args.format in ["both", "amp"]:
        amp_html = generate_amp_blog_post(ide_data)
        amp_path = out_dir / f"{slug}_blogger_post.html"
        amp_path.write_text(amp_html, encoding="utf-8")
        print(f"Generated AMP Blog Post: {amp_path}")

    if args.format in ["both", "video"]:
        video_spec = generate_google_flow_spec(ide_data)
        spec_json_path = out_dir / f"{slug}_google_flow_spec.json"
        spec_json_path.write_text(json.dumps(video_spec, indent=2), encoding="utf-8")

        # Convert to readable Markdown spec as well
        spec_md = f"# Google Flow Video Spec: {video_spec['title']}\n\n"
        spec_md += f"**Target IDE**: {video_spec['target_ide']}\n"
        spec_md += f"**Pricing**: {video_spec['pricing_model']}\n"
        spec_md += f"**YouTube Channel**: {YOUTUBE_CHANNEL_URL}\n"
        spec_md += f"**Blogger Post**: {BLOGGER_SITE_URL}\n\n"
        spec_md += "## YouTube Description\n```\n" + video_spec['description'] + "\n```\n\n"
        spec_md += "## Scene-by-Scene Visual Prompts\n\n"
        for scene in video_spec["scenes"]:
            spec_md += f"### Scene {scene['scene_number']} ({scene['timecode']})\n"
            spec_md += f"- **Visual Prompt (Google Flow)**: `{scene['visual_prompt']}`\n"
            spec_md += f"- **Camera Movement**: {scene['camera_movement']}\n"
            spec_md += f"- **On-Screen Text**: {scene['onscreen_text'].replace('\n', ' | ')}\n"
            spec_md += f"- **Voiceover Script**: \"{scene['voiceover_script']}\"\n"
            spec_md += f"- **Audio/SFX**: {scene['audio_cues']}\n\n"

        spec_md_path = out_dir / f"{slug}_google_flow_spec.md"
        spec_md_path.write_text(spec_md, encoding="utf-8")
        print(f"Generated Google Flow Video Spec: {spec_json_path} & {spec_md_path}")

if __name__ == "__main__":
    main()
